"""
Bake the Vehicle tab's car figures (ZeD-UI, Oct 13 2026).

Reads the vanilla mechanics overlay layers (media/ui/vehicles/mechanic overlay/,
one 263x600 white-silhouette PNG per part and body shape) and writes, per layer:
  zm_<name>.png      scanline fill (2 rows on / 2 rows off) with a solid 2 px rim
  <name>_rim.png  the rim alone (missing parts, not-yet-inspected cars)
and for each "<prefix>base.png" only the light line art (the car outline and the
callout boxes), as <prefix>base.png.
All layers are scaled by K, cropped to their bounding box, and the scanline
phase follows the shared canvas row, so stripes line up across layers.
Anchors (crop origin and size per layer, union box per body shape) go to
42/media/lua/client/ZeD/MechFigs.lua as ZeD.MechFigs.

Usage:  py -3.14 ZeDUI/tools/mechanics/bake_mech_figs.py [vanilla_overlay_dir]
"""
import os, sys
import numpy as np
from PIL import Image

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
SRC = sys.argv[1] if len(sys.argv) > 1 else r"E:\Project Zomboid\SteamApps\common\ProjectZomboid\media\ui\vehicles\mechanic overlay"
OUT_TEX = os.path.join(ROOT, "42", "media", "textures", "ZeD", "mech")
OUT_LUA = os.path.join(ROOT, "42", "media", "lua", "client", "ZeD", "MechFigs.lua")
FILE_PREFIX = "zm_"   # vanilla's packed UI textures share these base names; getTexture would resolve to them
K = 0.95          # canvas scale: a 513 px tall car lands near 488 px = 244 design units at 2x
RIM = 2           # rim thickness in baked px (1 design unit at the 2x root)
OFF_ALPHA = 0.10  # the "off" scanline rows keep a faint body

def erode(m, n):
    out = m.copy()
    for _ in range(n):
        p = np.pad(out, 1, constant_values=False)
        out = (p[1:-1, 1:-1] & p[:-2, 1:-1] & p[2:, 1:-1] & p[1:-1, :-2] & p[1:-1, 2:])
    return out

def save(arr_alpha, path):
    h, w = arr_alpha.shape
    rgba = np.zeros((h, w, 4), dtype=np.uint8)
    rgba[..., :3] = 255
    rgba[..., 3] = np.clip(arr_alpha * 255 + 0.5, 0, 255).astype(np.uint8)
    Image.fromarray(rgba, "RGBA").save(path, optimize=True)

def main():
    os.makedirs(OUT_TEX, exist_ok=True)
    files = sorted(f for f in os.listdir(SRC) if f.lower().endswith(".png"))
    anchors, unions = {}, {}
    for f in files:
        name = f[:-4]
        im = Image.open(os.path.join(SRC, f)).convert("RGBA")
        W, H = round(im.width * K), round(im.height * K)
        im = im.resize((W, H), Image.LANCZOS)
        a = np.asarray(im, dtype=np.float32) / 255.0
        alpha = a[..., 3]
        lum = (a[..., 0] + a[..., 1] + a[..., 2]) / 3.0
        is_base = name.endswith("_base") or name.endswith("base")
        if is_base:
            mask = alpha * lum                      # light line art only
            mask = np.where(mask > 0.35, mask, 0.0)
        else:
            mask = alpha
        ys, xs = np.nonzero(mask > 0.02)
        if len(xs) == 0:
            continue
        x0, x1, y0, y1 = xs.min(), xs.max() + 1, ys.min(), ys.max() + 1
        m = mask[y0:y1, x0:x1]
        prefix = name[: name.index("_") + 1] if "_" in name else name
        if is_base:
            save(m, os.path.join(OUT_TEX, FILE_PREFIX + name + ".png"))
        else:
            solid = m > 0.5
            rim = solid & ~erode(solid, RIM)
            rows = (np.arange(y0, y1) // 2) % 2 == 0          # canvas-phase scanlines
            scan = np.where(rows[:, None], 1.0, OFF_ALPHA)
            fill = np.where(rim, 1.0, np.where(solid, scan, 0.0)) * np.clip(m * 1.4, 0, 1)
            save(fill, os.path.join(OUT_TEX, FILE_PREFIX + name + ".png"))
            save(rim.astype(np.float32), os.path.join(OUT_TEX, FILE_PREFIX + name + "_rim.png"))
        anchors[name] = (int(x0), int(y0), int(x1 - x0), int(y1 - y0))
        u = unions.get(prefix)
        unions[prefix] = (min(u[0], x0), min(u[1], y0), max(u[2], x1), max(u[3], y1)) if u else (x0, y0, x1, y1)

    with open(OUT_LUA, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("-- GENERATED by ZeDUI/tools/mechanics/bake_mech_figs.py - do not edit.\n")
        fh.write("-- Vehicle tab car figures: per-layer crop origin + size in baked canvas px\n")
        fh.write(f"-- (vanilla 263x600 overlay canvas x {K}); union box per body-shape prefix.\n")
        fh.write("ZeD = ZeD or {}\nZeD.MechFigs = {\n  K = %s,\n  layers = {\n" % K)
        for k in sorted(anchors):
            x, y, w, h = anchors[k]
            fh.write(f'    ["{k}"] = {{ x = {x}, y = {y}, w = {w}, h = {h} }},\n')
        fh.write("  },\n  unions = {\n")
        for p in sorted(unions):
            x0, y0, x1, y1 = unions[p]
            fh.write(f'    ["{p}"] = {{ x = {int(x0)}, y = {int(y0)}, w = {int(x1 - x0)}, h = {int(y1 - y0)} }},\n')
        fh.write("  },\n}\nreturn ZeD.MechFigs\n")
    print(f"baked {len(anchors)} layers for {len(unions)} body shapes -> {OUT_TEX}")
    print(f"anchors -> {OUT_LUA}")

if __name__ == "__main__":
    main()


# ---------------------------------------------------------------------------
# Grid box behind the figure: the Health tab's perspective-box look, drawn for
# the car's aspect (120 x 244 design units -> 240 x 488 px at the 2x root).
# White lines; the game tints them with textDim, so all three bases work.
# ---------------------------------------------------------------------------
def bake_gridbox(path, W=240, H=488, inset=26, step=32):
    from PIL import ImageDraw
    img = Image.new("RGBA", (W, H), (255, 255, 255, 0))
    d = ImageDraw.Draw(img)
    line = (255, 255, 255, 255)
    soft = (255, 255, 255, 120)
    d.rectangle([0, 0, W - 1, H - 1], outline=line, width=1)
    d.rectangle([inset, inset, W - 1 - inset, H - 1 - inset], outline=line, width=1)
    for (x0, y0, x1, y1) in [(0, 0, inset, inset), (W - 1, 0, W - 1 - inset, inset),
                             (0, H - 1, inset, H - 1 - inset), (W - 1, H - 1, W - 1 - inset, H - 1 - inset)]:
        d.line([x0, y0, x1, y1], fill=line, width=1)
    for x in range(inset + step, W - inset, step):          # back plane grid
        d.line([x, inset, x, H - 1 - inset], fill=soft, width=1)
    for y in range(inset + step, H - inset, step):
        d.line([inset, y, W - 1 - inset, y], fill=soft, width=1)
    for x in range(inset + step, W - inset, step):          # floor and ceiling rays
        fx = round(x / W * (W - 1))
        d.line([x, H - 1 - inset, fx, H - 1], fill=soft, width=1)
        d.line([x, inset, fx, 0], fill=soft, width=1)
    for y in range(inset + step, H - inset, step):          # wall rays
        fy = round(y / H * (H - 1))
        d.line([inset, y, 0, fy], fill=soft, width=1)
        d.line([W - 1 - inset, y, W - 1, fy], fill=soft, width=1)
    img.save(path, optimize=True)

if __name__ == "__main__":
    bake_gridbox(os.path.join(OUT_TEX, FILE_PREFIX + "gridbox.png"))
    print("gridbox -> " + os.path.join(OUT_TEX, FILE_PREFIX + "gridbox.png"))
