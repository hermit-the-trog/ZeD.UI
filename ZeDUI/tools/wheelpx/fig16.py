def _canvas():
    return [["."] * 16 for _ in range(16)]


def _put(g, *cells):
    for x, y in cells:
        if 0 <= x < 16 and 0 <= y < 16: g[y][x] = "#"


def _rect(g, x, y, w, h):
    for yy in range(y, y + h):
        for xx in range(x, x + w): _put(g, (xx, yy))


def _head(g, x0):
    """the template head: a 5 x 5 disc, rows 0-4, cols x0..x0+4"""
    _rect(g, x0 + 1, 0, 3, 1); _rect(g, x0, 1, 5, 3); _rect(g, x0 + 1, 4, 3, 1)


def _climb():
    g = _canvas()
    for x in (10, 14): _rect(g, x, 0, 1, 16)                       # the ladder
    for y in (1, 5, 9, 13): _rect(g, 10, y, 5, 1)
    _head(g, 4)
    _rect(g, 4, 6, 3, 5)                                           # trunk
    _put(g, (7, 6), (8, 5), (8, 4), (9, 3), (9, 2), (9, 1))        # the arm up to the rung
    _rect(g, 7, 9, 3, 2); _rect(g, 8, 11, 2, 2)                    # the front leg: thigh up, shin to the rung
    _rect(g, 4, 11, 2, 5)                                          # the back leg
    return ["".join(r) for r in g]


def _carry():
    g = _canvas()
    _head(g, 4)
    _rect(g, 5, 6, 3, 5)                                           # trunk
    _rect(g, 10, 5, 5, 5)                                          # the box
    _put(g, (8, 7), (9, 7))                                        # the arm out to it
    _rect(g, 5, 11, 2, 1); _put(g, (7, 11))                        # hips
    _put(g, (4, 12), (5, 12), (3, 13), (4, 13), (2, 14), (3, 14), (2, 15))   # back leg
    _put(g, (7, 12), (8, 12), (8, 13), (9, 13), (9, 14), (10, 14), (10, 15))  # front leg
    return ["".join(r) for r in g]


G16["climb"] = _climb()
G16["carry"] = _carry()
