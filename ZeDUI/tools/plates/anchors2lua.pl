#!/usr/bin/perl
# Converts the plate anchor JSON files into one Lua table module.
# usage: anchors2lua.pl <json dir> <prefix> <out.lua> <luaGlobal>
use strict; use warnings; use JSON::PP;
my ($dir, $prefix, $out, $global) = @ARGV;
opendir(my $dh, $dir) or die "no dir $dir";
my @files = sort grep { /^\Q$prefix\E.*\.json$/ } readdir($dh); closedir $dh;
sub lua {
  my ($v, $ind) = @_;
  if (ref $v eq 'HASH') {
    my @parts;
    for my $k (sort keys %$v) { my $key = ($k =~ /^[A-Za-z_][A-Za-z0-9_]*$/) ? $k : "[\"$k\"]"; push @parts, "$ind  $key = " . lua($v->{$k}, "$ind  "); }
    return "{\n" . join(",\n", @parts) . "\n$ind}";
  } elsif (ref $v eq 'ARRAY') { return "{ " . join(", ", map { lua($_, $ind) } @$v) . " }"; }
  elsif (!defined $v) { return "nil"; }
  elsif (JSON::PP::is_bool($v)) { return $v ? "true" : "false"; }
  elsif ($v =~ /^-?\d+(\.\d+)?$/) { return $v; }
  else { (my $s = $v) =~ s/\\/\\\\/g; $s =~ s/"/\\"/g; return "\"$s\""; }
}
open(my $fh, '>', $out) or die $!;
print $fh "-- GENERATED by ZeDUI/tools/plates/anchors2lua.pl from the locked v5 mockups. Do not edit by hand.\n";
print $fh "-- Each entry = one plate: static art in 42/media/textures/ZeD/<set>/<name>.png (2x), anchors for the live overlay.\n";
print $fh "$global = $global or {}\n";
for my $f (@files) {
  local $/; open(my $in, '<', "$dir/$f") or die $!; my $txt = <$in>; close $in;
  next unless length($txt) > 2;
  my $data = JSON::PP->new->decode($txt);
  (my $name = $f) =~ s/\.json$//;
  print $fh "$global.$name = " . lua($data, "") . "\n";
}
close $fh; print "wrote $out (" . scalar(@files) . " plates)\n";
