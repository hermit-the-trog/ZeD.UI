def compose35(base, mark):
    rows4 = B35[base]
    w = width(rows4)
    if mark in MB35:
        key = "commaT" if (mark == "comma" and base == "T") else mark
        return rows4 + [MB35[key]]
    return [M35[w][mark]] + rows4


def build():
    faces = read_base(SRC)
    out35, out57 = {}, {}
    for cp, base, mark in LATIN:
        if mark in MB57:
            out57[cp] = B57[base] + MB57[mark]
        else:
            out57[cp] = M57[width(B57[base])][mark] + B57[base]
        out35[cp] = compose35(base, mark)
    for cp in HAND_LATIN:
        out57[cp] = HAND57[cp]
        out35[cp] = HAND35[cp]
    for cp, latin in CYR_LATIN.items():
        out57[cp] = faces["57"][latin]
        out35[cp] = faces["35"][latin]
    for cp, (base, mark) in CYR_MARKED.items():
        # Yo and Yi use the Latin letters' compressed bases; short I its own
        out57[cp] = M57[width(B57[base])][mark] + B57[base]
        out35[cp] = [M35[width(B35[base])][mark]] + B35[base]
    for cp in CYR_HAND:
        out57[cp] = HAND57[cp]
        out35[cp] = HAND35[cp]
    for cp in SIGNS:
        out57[cp] = HAND57[cp]
        if cp in HAND35:       # the 3 x 5 face already has % and #-style signs it was drawn with
            out35[cp] = HAND35[cp]
    for cp in SIGNS35_ONLY:
        out35[cp] = HAND35[cp]
    # the face lacks these signs; keep only what the base file does not already have
    for face, table in (("35", out35), ("57", out57)):
        for cp in list(table):
            if chr(cp) in faces[face]:
                del table[cp]
    return faces, out35, out57


def check(faces, out35, out57):
    problems = []
    for face, table, h in (("35", out35, 5), ("57", out57, 7)):
        for cp, rows in table.items():
            w = len(rows[0])
            if len(rows) != h:
                problems.append("%s U+%04X has %d rows" % (face, cp, len(rows)))
            for r in rows:
                if len(r) != w or set(r) - set("01"):
                    problems.append("%s U+%04X ragged or bad row %r" % (face, cp, r))
    for ch in REQUIRED:
        if ord(ch) not in out35 or ord(ch) not in out57:
            problems.append("missing U+%04X %s" % (ord(ch), ch))
    return problems


def lua_text(out35, out57):
    lines = [
        "-- GENERATED by ZeDUI/tools/i18n/pixel_glyphs_gen.py - do not edit; change the generator and run it again.",
        "-- The pixel faces' extra letters: accented Latin capitals, Cyrillic capitals and a few signs, drawn in the",
        "-- style of PixelFonts.lua (same height; accents take rows from the cell and the base letter is compressed).",
        "-- Keys are Unicode code points, so this file holds no non-ASCII text. They are merged into",
        "-- ZeD.PixelFonts under string.char(code point); a glyph the base file already has is never replaced.",
        "require \"ZeD/PixelFonts\"",
        "ZeD = ZeD or {}",
        "local EXT = {",
    ]
    for face, table in (("35", out35), ("57", out57)):
        lines.append('  ["%s"] = {' % face)
        for cp in sorted(table):
            rows = ", ".join('"%s"' % r for r in table[cp])
            lines.append("    [%d] = { %s },   -- U+%04X" % (cp, rows, cp))
        lines.append("  },")
    lines += [
        "}",
        "for face, glyphs in pairs(EXT) do",
        "    local F = ZeD.PixelFonts and ZeD.PixelFonts[face]",
        "    if F then",
        "        for cp, rows in pairs(glyphs) do",
        "            local ch = string.char(cp)",
        "            if F[ch] == nil then F[ch] = rows end",
        "        end",
        "    end",
        "end",
        "",
    ]
    return "\n".join(lines)


def main():
    faces, out35, out57 = build()
    problems = check(faces, out35, out57)
    if problems:
        print("\n".join(problems))
        sys.exit(1)
    text = lua_text(out35, out57)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote %s: %d glyphs in 35, %d in 57" % (OUT, len(out35), len(out57)))


if __name__ == "__main__":
    main()
