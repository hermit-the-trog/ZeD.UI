def read_base(path):
    """{face: {char: rows}} from the generated PixelFonts.lua."""
    text = open(path, encoding="utf-8").read()
    faces = {}
    for face in ("35", "57"):
        m = re.search(r'\["%s"\] = \{(.*?)\n  \},' % face, text, re.S)
        body = m.group(1)
        glyphs = {}
        for line in body.splitlines():
            line = line.strip()
            if not line or line.startswith("--"):
                continue
            km = re.match(r'(?:\["(.)"\]|\[string\.char\((\d+)\)\]|([A-Za-z])) = \{ (.*) \},?$', line)
            if not km:
                raise SystemExit("cannot parse: " + line)
            key = km.group(1) or (chr(int(km.group(2))) if km.group(2) else km.group(3))
            glyphs[key] = re.findall(r'"([01]+)"', km.group(4))
        faces[face] = glyphs
    return faces


def width(rows):
    return len(rows[0])


def padto(rows, w):
    return [r + "0" * (w - len(r)) for r in rows]


