"""
Writes 42/media/lua/client/ZeD/PixelFontsExt.lua: the extra letters of ZeD's two pixel faces.

The base faces (A-Z, 0-9, a few signs) live in PixelFonts.lua, which is generated by
tools/dashpx/export_lua.py and must not be edited. This script reads that file, builds the
accented Latin capitals, the Cyrillic capitals and a handful of signs in the same style, and
writes them to PixelFontsExt.lua, keyed by Unicode code point so the Lua file holds no
non-ASCII text.

How the glyphs are built
  - Same height as the face: 5 rows for the 3 x 5 face ("35"), 7 rows for the 5 x 7 face ("57").
  - Accents above take rows from the top of the cell; the base letter is drawn compressed to
    the rows that are left (4 rows in the 3 x 5 face, 5 rows in the 5 x 7 face).
  - Marks below (cedilla, comma) take rows from the bottom the same way.
  - Cyrillic letters that look like a Latin capital reuse that capital's rows.
  - Anything that composes badly is drawn by hand in HAND35 / HAND57 below.

To change a glyph: edit the tables in this file and run it again. The contact sheet is
tools/i18n/pixel_glyphs_sheet.py.
"""
