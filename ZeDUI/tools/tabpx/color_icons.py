"""The window tabs' icons in color (the director, Nov 25 2026): the pictures and their data.

    python -I ZeDUI/tools/tabpx/color_icons.py <art.json>

art.json: the mock-up's ART table (ZeDUI/mockups/container_tabs_color_v4.html, `const ART`): per tab id a 16 x 16
pixel map in three letters (a, b, c) and two palettes, "pal" for Dark and High contrast and "palLight" (with its own
map "pxLight") drawn darker for Light. Equipment is the olive field jacket (the director's pick, art "equip_field").

Writes, for each tab:
  media/textures/ZeD/TabIcons/color/<id>.png        the Dark set, full color
  media/textures/ZeD/TabIcons/color/<id>_light.png  the Light set
  media/textures/ZeD/TabIcons/color/<id>_sh.png     the drop shadow mask (the icon's shape, white; drawn black)
and 42/media/lua/client/ZeD/ZeD_TabColorArt.lua: each set's three colors and how many pixels each covers, so the
lit panel can take whichever set stands off it better (ZeD.TabPx.drawIcon). Run with the ComfyUI venv's Python.
"""
import json
import os
import sys

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", "..", ".."))
TEX = os.path.join(ROOT, "42", "media", "textures", "ZeD", "TabIcons", "color")
LUA = os.path.join(ROOT, "42", "media", "lua", "client", "ZeD", "ZeD_TabColorArt.lua")
TABS = ["loot", "equip", "health", "thermal", "identity", "journal", "skills",
        "craft", "build", "furniture", "maps", "forage", "animals", "vehicle"]
ART_OF = {"equip": "equip_field"}


def rgb(h):
    return int(h[1:3], 16), int(h[3:5], 16), int(h[5:7], 16)


def picture(px, pal):
    im = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
    counts = [0, 0, 0]
    for y, row in enumerate(px):
        for x, ch in enumerate(row):
            if ch == ".":
                continue
            i = "abc".index(ch)
            counts[i] += 1
            im.putpixel((x, y), rgb(pal[i]) + (255,))
    return im, counts


def main():
    art = json.load(open(sys.argv[1], encoding="utf-8"))
    os.makedirs(TEX, exist_ok=True)
    rows = []
    for tab in TABS:
        a = art[ART_OF.get(tab, tab)]
        dark, dc = picture(a["px"], a["pal"])
        light, lc = picture(a.get("pxLight", a["px"]), a.get("palLight", a["pal"]))
        dark.save(os.path.join(TEX, tab + ".png"))
        light.save(os.path.join(TEX, tab + "_light.png"))
        sh = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
        for y, row in enumerate(a["px"]):
            for x, ch in enumerate(row):
                if ch != ".":
                    sh.putpixel((x, y), (255, 255, 255, 255))
        sh.save(os.path.join(TEX, tab + "_sh.png"))

        def lua_set(pal, counts):
            cs = ", ".join("{ r = %.4f, g = %.4f, b = %.4f, n = %d }" % (r / 255, g / 255, b / 255, n)
                           for (r, g, b), n in zip((rgb(h) for h in pal), counts))
            return "{ " + cs + " }"
        rows.append("    %s = { dark = %s,\n        light = %s }," % (
            tab, lua_set(a["pal"], dc), lua_set(a.get("palLight", a["pal"]), lc)))
    head = [
        "-- ZeD-UI/42/media/lua/client/ZeD/ZeD_TabColorArt.lua",
        "-- ============================================================================",
        "-- THE WINDOW TABS' COLOR ICONS: each set's three colors and how many pixels each covers (the director, Nov 25",
        "-- 2026; mock-up ZeDUI/mockups/container_tabs_color_v4.html). Generated by ZeDUI/tools/tabpx/color_icons.py",
        "-- with the pictures in media/textures/ZeD/TabIcons/color/: do not edit by hand. ZeD.TabPx.drawIcon reads it",
        "-- to put on the lit panel whichever set stands off the panel better. Pure ASCII.",
        "-- ============================================================================",
        "ZeD = ZeD or {}",
        "ZeD.TabColorArt = {",
    ]
    with open(LUA, "w", encoding="ascii", newline="\n") as f:
        f.write("\n".join(head + rows + ["}", ""]))
    print("wrote %d tabs to %s and %s" % (len(TABS), TEX, LUA))


if __name__ == "__main__":
    main()
