-- which part is under canvas point (cx, cy): the generated map (the rectangles overlap; the map follows the bones,
-- a click within a few pixels of a bone counts). The rectangles stay for the gamepad's focus boxes.
local HIT_CELL = 2
local function mapPart(fig, cx, cy)
    local map = fig.isFemale and F_HITMAP or M_HITMAP
    local row = map[math.floor(cy / HIT_CELL) + 1]
    if not row then return nil end
    local ch = string.byte(row, math.floor(cx / HIT_CELL) + 1)
    if not ch or ch == 46 then return nil end            -- "." = no part
    return PART_ORDER[ch - 96]
end

