function ZeD_BodyFigure:new(x, y, width, height, playerNum)
    local o = ISPanel:new(x, y, width, height)
    setmetatable(o, self)
    self.__index = self

    o.playerNum = playerNum
    o.isFemale = false
    o.drawBorder = false
    o.borderColor = {r=0, g=0, b=0, a=0}
    o.backgroundColor = {r=0, g=0, b=0, a=0}

    o.colorMap = {}       -- displayName -> {r, g, b, a}
    o.wounds = {}         -- displayName -> the part's wounds (woundsOf), drawn over the parts
    o.skinTone = 0        -- the character's skin tone (setSkinTone): the skin under the marks
    o.selectedPart = nil  -- display name of hovered part

    o.onPartHover = nil
    o.onPartClick = nil

    o.textures = {}       -- suffix -> texture
    o.texturesLoaded = false
    o.activeLayout = M_LAYOUT

    return o
end

-- ============================================================================
-- TEXTURE LOADING
