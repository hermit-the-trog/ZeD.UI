-- a per-part picture with its top left at canvas point at = { x, y }, tinted (the skin) or as drawn
local function drawWoundPic(panel, name, at, xOff, yOff, s, tint)
    local tex = at and woundTex(name)
    if not tex then return end
    local x, y = xOff + math.floor(at[1] * s), yOff + math.floor(at[2] * s)
    if tint then
        panel:drawTextureScaledUniform(tex, x, y, s, 1, tint.r, tint.g, tint.b)
    else
        panel:drawTextureScaledUniform(tex, x, y, s, 1, 1, 1, 1)
    end
end

-- a mark's picture (MARK_C each way from its middle) with its middle at canvas point (cx, cy)
local function drawMark(panel, name, cx, cy, xOff, yOff, s)
    local tex = woundTex(name)
    if not tex then return end
    panel:drawTextureScaledUniform(tex, xOff + math.floor((cx - MARK_C) * s), yOff + math.floor((cy - MARK_C) * s), s,
        1, 1, 1, 1)
end

-- a mark onto a part's list, the list made with its first mark; at most two (the first found are the most serious)
local function addMark(marks, kind)
    if not marks then return { kind } end
    if #marks < 2 then marks[#marks + 1] = kind end
    return marks
end

--- The wounds the figure draws on one part, from what the Health tab's list read of it. HealthTab's
--- classifyConditions fills `seen` as it reads the game's BodyPart, once a flag, so the figure reads nothing again;
--- what the list hides, the figure hides. seen:
---   bandaged, clean   gauze on the part; clean while the bandage has life left
---   splint, fracture  a splint on the part; a fracture in its bone
---   bitten, deep, stitched, bullet, glass, cut, burn, scratch, bleed    the wounds the part has
---   infected          an infection the list names (by the looker's First Aid, as the list rules)
---   held              another mod holds the part's diagnosis back: only the care given shows
--- Returns nil when there is nothing to draw (most parts), else the table setPartWounds takes:
---   bandage = "clean" | "dirty"   gauze round the part; it covers every wound under it
---   splint = true                 two boards tied along the part
---   fracture = true               a crack across the part's bone
---   marks = { kind, kind }        at most two, the most serious first (MARK_ORDER)
---   bleed = true                  blood running down from the last mark
---   infected = true               a yellow-green ring round the first mark
function ZeD_BodyFigure.woundsFrom(seen)
    if not seen then return nil end
    local w = nil                           -- (made only for a part with something to draw: most parts have nothing)
    if seen.bandaged then
        -- (the list's "Dirty Bandage": the bandage's life has run out)
        w = { bandage = seen.clean and "clean" or "dirty" }
    end
    if seen.splint then
        w = w or {}
        w.splint = true
    end
    if seen.held then
        -- held back: the care alone (the bandage, the splint, and the stitches when no gauze covers them)
        if seen.stitched and not seen.bandaged then
            w = w or {}
            w.marks = { "stitch" }
        end
        return w
    end
    if seen.fracture then
        w = w or {}
        w.fracture = true
    end
    if seen.bandaged then return w end      -- the gauze covers the wounds
    -- the marks, most serious first (MARK_ORDER)
    local marks = nil
    if seen.bitten then marks = addMark(marks, "bite") end
    if seen.deep and not seen.stitched then marks = addMark(marks, "deep") end   -- stitched, it shows as its stitches
    if seen.stitched then marks = addMark(marks, "stitch") end
    if seen.bullet then marks = addMark(marks, "bullet") end
    if seen.glass then marks = addMark(marks, "glass") end
    if seen.cut then marks = addMark(marks, "cut") end
    if seen.burn then marks = addMark(marks, "burn") end
    if seen.scratch then marks = addMark(marks, "scratch") end
    if marks then
        w = w or {}
        w.marks = marks
    end
    if seen.bleed then
        w = w or {}
        w.bleed = true
    end
    -- an infection the list names rings the first mark
    if marks and seen.infected then w.infected = true end
    return w
end

--- The skin tone of a character: the game's getSkinTextureIndex, 0 to 4 (0 when the game gives none)
function ZeD_BodyFigure.skinToneOf(character)
    local ok, i = pcall(function() return character:getHumanVisual():getSkinTextureIndex() end)
    return (ok and tonumber(i)) or 0
end

--- A part's wounds, the table woundsFrom makes (nil clears them). Set every part each read, as setPartColor.
function ZeD_BodyFigure:setPartWounds(displayName, w)
    self.wounds[displayName] = w
end

function ZeD_BodyFigure:clearWounds()
    self.wounds = {}
end

--- The color of the skin under the marks: the character's getSkinTextureIndex (0 to 4)
function ZeD_BodyFigure:setSkinTone(index)
    index = math.floor(tonumber(index) or 0)
    if index < 0 then index = 0 elseif index > #SKIN_TINT - 1 then index = #SKIN_TINT - 1 end
    self.skinTone = index
end

--- The wounds over the parts, in six passes with every part in the figure's order each pass, so one part's gauze
--- never covers a neighbor's mark: 1 cracks, 2 bandages, 3 skin (tinted by the skin tone), 4 infected rings, 5 marks
--- and the bleeding under the last, 6 splints.
function ZeD_BodyFigure:_drawWounds(panel, xOff, yOff, s)
    local wounds = self.wounds
    if not wounds then return end
    -- nothing hurt (the usual case): return at once. Kahlua has no next(), so a pairs loop tests for any entry.
    local any = false
    for _ in pairs(wounds) do any = true break end
    if not any then return end
    local sex = self.isFemale and "f" or "m"
    local places = self.isFemale and F_WOUNDS or M_WOUNDS
    local tone = SKIN_TINT[(self.skinTone or 0) + 1] or SKIN_TINT[1]
    for pass = 1, 6 do
        for _, entry in ipairs(self.activeLayout) do
            local sfx = entry.suffix
            local w = wounds[SUFFIX_TO_DISPLAY[sfx]]
            local g = w and places[sfx]
            if g then
                local names = partNames(sex, sfx)
                local marks = w.marks
                local n = marks and math.min(#marks, 2) or 0
                if pass == 1 then
                    if w.fracture then drawWoundPic(panel, names.fracture, g.fracture, xOff, yOff, s) end
                elseif pass == 2 then
                    if w.bandage then
                        local pic = (w.bandage == "dirty") and "bandage-dirty" or "bandage"
                        drawWoundPic(panel, names[pic], g[pic], xOff, yOff, s)
                    end
                elseif pass == 3 then
                    if n > 0 or w.bleed then
                        local pic = SKIN_PIC[math.max(1, n)][w.bleed == true]
                        drawWoundPic(panel, names[pic], g[pic], xOff, yOff, s, tone)
                    end
                elseif pass == 4 then
                    local mk = (w.infected and n > 0) and MARK_NAMES[marks[1]]
                    if mk then
                        local at = g.slots[n][1]
                        drawMark(panel, mk.infected, at[1], at[2], xOff, yOff, s)
                    end
                elseif pass == 5 then
                    local slots = g.slots[math.max(1, n)]
                    for i = 1, n do
                        local mk = MARK_NAMES[marks[i]]
                        if mk then drawMark(panel, mk.mark, slots[i][1], slots[i][2], xOff, yOff, s) end
                    end
                    if w.bleed then
                        -- below and right of the last mark (with none, of the part's own place)
                        local at = slots[math.max(1, n)]
                        drawMark(panel, BLEED_NAME, at[1] + BLEED_DX, at[2] + BLEED_DY, xOff, yOff, s)
                    end
                elseif pass == 6 then
                    if w.splint and g.splint then drawWoundPic(panel, names.splint, g.splint, xOff, yOff, s) end
                end
            end
        end
    end
end

