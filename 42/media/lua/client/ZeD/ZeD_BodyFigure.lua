-- the pictures, loaded the first time each is drawn, nearest-filtered like the parts (false: missing, asked once)
local _woundTex = {}
local function woundTex(name)
    local t = _woundTex[name]
    if t == nil then
        t = Texture.getSharedTexture(WOUND_DIR .. name, NEAREST) or false
        _woundTex[name] = t
    end
