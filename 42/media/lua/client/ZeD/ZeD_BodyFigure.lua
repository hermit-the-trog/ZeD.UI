-- ============================================================================
-- SCALE + OFFSET (fit canvas into panel)
-- ============================================================================

function ZeD_BodyFigure:getDrawParams()
    local panelW = self:getWidth()
    local panelH = self:getHeight()
    local cw, ch = _canvasFor(self)
    -- the largest whole multiple of the canvas that fits the panel
    local s = _fit(panelW, panelH)
    -- Center in panel
    local scaledW = math.floor(cw * s)
    local scaledH = math.floor(ch * s)
    local xOff = math.floor((panelW - scaledW) / 2)
    local yOff = math.floor((panelH - scaledH) / 2)
    return s, xOff, yOff
end

-- ============================================================================
-- HIT TESTING (uses per-part hit regions, scaled)
-- ============================================================================

function ZeD_BodyFigure:hitTest(mx, my)
    local s, xOff, yOff = self:getDrawParams()

    -- Convert mouse to canvas coords
    local cx = (mx - xOff) / s
    local cy = (my - yOff) / s

    local cw, ch = _canvasFor(self)
    if cx < 0 or cx > cw or cy < 0 or cy > ch then
        return nil
    end

    local sfx = mapPart(self, cx, cy)
    return sfx and SUFFIX_TO_DISPLAY[sfx] or nil
end

-- ============================================================================
-- RENDER
-- ============================================================================

function ZeD_BodyFigure:render()
    ISPanel.render(self)
    if not self.texturesLoaded then
        self:loadTextures()
    end
    local s, xOff, yOff = self:getDrawParams()
    local bg = self:_background()
    local w, h = math.floor(CANVAS_W * s), math.floor(CANVAS_H * s)
    if bg then
        local tint = ZeD.colorBlend(ZeD.T.iconWhite, ZeD.T.accent, 0.45)
        self:drawTextureScaled(bg, xOff, yOff, w, h, 1.0, tint.r, tint.g, tint.b)
    end
    if self.skeletonTex then self:drawTextureScaled(self.skeletonTex, xOff, yOff, w, h, 1, 1, 1, 1) end
    self:_drawParts(self, xOff, yOff, s)
    self:_drawWounds(self, xOff, yOff, s)
end

-- ============================================================================
-- DRAW-AT: Render onto an external panel at a given position.
-- Used when the figure is NOT a child panel — drawn inside the parent's
-- stencil rect so it clips properly with scroll.
-- ============================================================================

function ZeD_BodyFigure:drawAt(panel, px, py, pw, ph)
    if not self.texturesLoaded then
        self:loadTextures()
    end

    -- fit the canvas into the given rect at a whole multiple (the pixel art stays square)
    local s = _fit(pw, ph)
    local scaledW = math.floor(CANVAS_W * s)
    local scaledH = math.floor(CANVAS_H * s)
    local xOff = px + math.floor((pw - scaledW) / 2)
    local yOff = py + math.floor((ph - scaledH) / 2)

    -- Store draw params for hitTestAt
    self._drawAtS = s
    self._drawAtX = xOff
    self._drawAtY = yOff

    -- 1. the height ruler and the body's outline, in the theme's colour
    local bg = self:_background()
    if bg then
        local tint = ZeD.colorBlend(ZeD.T.iconWhite, ZeD.T.accent, 0.45)
        panel:drawTextureScaled(bg, xOff, yOff, scaledW, scaledH, 1.0, tint.r, tint.g, tint.b)
    end
    -- 2. the skeleton, lit, as drawn
    if self.skeletonTex then
        panel:drawTextureScaled(self.skeletonTex, xOff, yOff, scaledW, scaledH, 1, 1, 1, 1)
    end
    -- 3. the parts, tinted by the tab
    self:_drawParts(panel, xOff, yOff, s)
    -- 4. the wounds and their care, over the parts (only where the tab set them)
    self:_drawWounds(panel, xOff, yOff, s)
end

-- Gamepad support: return panel-local rects for every hittable body
-- part, using the current drawAt transform. Empty list if the figure has
-- not been drawn yet (first frame after tab switch) — caller drops the
-- body-part zone entirely rather than stamping phantom rects.
function ZeD_BodyFigure:getPartRects()
    local s = self._drawAtS
    if not s or s <= 0 then return {} end
    local xOff = self._drawAtX or 0
    local yOff = self._drawAtY or 0
    -- (the last answer while the figure stands where it stood: the tabs and their stops ask every frame;
    -- a new place gets a new list, so a list kept from before keeps its rects)
    local k = self._rectsKey
    if k and k.s == s and k.x == xOff and k.y == yOff and k.layout == self.activeLayout then return k.out end
    local out = {}
    for _, e in ipairs(self.activeLayout) do
        local displayName = SUFFIX_TO_DISPLAY[e.suffix]
        if displayName then
            local h = e.hit or e
            out[#out + 1] = {
                name = displayName,
                x = xOff + math.floor(h.x * s),
                y = yOff + math.floor(h.y * s),
                w = math.floor(h.w * s),
                h = math.floor(h.h * s),
            }
        end
    end
    self._rectsKey = { s = s, x = xOff, y = yOff, layout = self.activeLayout, out = out }
    return out
end

-- Hit test using drawAt coordinates (mouse coords relative to the parent panel)
function ZeD_BodyFigure:hitTestAt(mx, my)
    local s = self._drawAtS or 1
    local xOff = self._drawAtX or 0
    local yOff = self._drawAtY or 0

    local cx = (mx - xOff) / s
    local cy = (my - yOff) / s

    local cw, ch = _canvasFor(self)
    if cx < 0 or cx > cw or cy < 0 or cy > ch then
        return nil
    end

    local sfx = mapPart(self, cx, cy)
    return sfx and SUFFIX_TO_DISPLAY[sfx] or nil
end

-- ============================================================================
-- MOUSE HANDLING
-- ============================================================================

function ZeD_BodyFigure:onMouseMove(dx, dy)
    ISPanel.onMouseMove(self, dx, dy)
    local hitPart = self:hitTest(self:getMouseX(), self:getMouseY())
    if hitPart ~= self.selectedPart then
        self.selectedPart = hitPart
        if self.onPartHover then
            self.onPartHover(hitPart)
        end
    end
end

function ZeD_BodyFigure:onMouseMoveOutside(dx, dy)
    ISPanel.onMouseMoveOutside(self, dx, dy)
    if self.selectedPart ~= nil then
        self.selectedPart = nil
        if self.onPartHover then
            self.onPartHover(nil)
        end
    end
end

function ZeD_BodyFigure:onMouseDown(x, y)
    ISPanel.onMouseDown(self, x, y)
    if self.selectedPart and self.onPartClick then
        self.onPartClick(self.selectedPart)
    end
end
