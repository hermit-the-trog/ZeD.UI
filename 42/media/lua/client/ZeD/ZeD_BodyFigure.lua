function ZeD_BodyFigure:setSex(isFemale)
    if isFemale ~= self.isFemale then
        self.isFemale = isFemale
        self.activeLayout = isFemale and F_LAYOUT or M_LAYOUT
        self.texturesLoaded = false
    end
end

function ZeD_BodyFigure:loadTextures()
    local prefix = self.isFemale and "f" or "m"
    self.textures = {}
    for _, entry in ipairs(self.activeLayout) do
        self.textures[entry.suffix] = Texture.getSharedTexture(DIR .. prefix .. "-" .. entry.suffix .. ".png", NEAREST)
    end
    self.skeletonTex = Texture.getSharedTexture(DIR .. prefix .. "-skeleton.png", NEAREST)
    self._bgTex = nil                                   -- the background follows the sex too
    self.texturesLoaded = true
end

-- the height ruler and outline for this sex and theme base
function ZeD_BodyFigure:_background()
    -- (the base of the table in use: a split view player's own theme draws their figure, PlayerTheme.lua)
    local isLight = ((ZeD.T and ZeD.T.baseKey) or ZeD.currentBase) == "light"
    local key = (self.isFemale and "f" or "m") .. (isLight and "light" or "dark")
    if self._bgKey ~= key then
        self._bgTex = Texture.getSharedTexture(DIR .. "fig-bg-" .. (self.isFemale and "f" or "m") .. "-" ..
            (isLight and "light" or "dark") .. ".png", NEAREST)
        self._bgKey = key
    end
    return self._bgTex
end

-- ============================================================================
-- THE HEIGHT CHART (Figure frame, the director, Nov 22 2026: "Draw a diagram
-- background. Very simple, just to fill in the empty white space on each
-- side." and "it should have old handwritten script identifying each part.
-- This does not need to be legible. This is very much just a hint at that.")
-- Behind the figure, in the margins of its frame: the ruler's half-foot lines
-- carried out to either side (each foot stronger than the half between), the
-- floor right across under the feet, and a word of old script on a line
-- beside each part (the parts on the character's right side, the neck and
-- the belly at the left; the rest at the right), all in the ruler's ink and
-- tint. A margin too narrow for its words keeps its lines. The tables and the
-- script's pictures are d_chart.py's (ZeDUI/tools/physpx).
-- ============================================================================

local CHART = {   -- generated by d_chart.py, in canvas (art) pixels
    -- the half-foot lines are in their picture (fig-chart-lines.png, a column stretched along each side),
    -- on rows 248, 226, 205, 183, 162, 140, 119, 97, 76, 54, 33, 11 (half a foot up to 6 ft, each foot stronger)
    -- the floor under the soles: its row, its alpha, and the columns the ruler's own floor tick takes
    floor = 269, floorA = 0.30, floorGap = { 7, 14 },
    -- the art pixels the lines keep clear of the frame's line and of the canvas; the script's alpha
    margin = 2, noteA = 0.30,
    -- the ruler's ink on the dark bases and on Light (tinted by the theme)
    inkDark = { 1, 1, 1 }, inkLight = { 24 / 255, 24 / 255, 26 / 255 },
    -- each side's script picture (fig-notes-<s>-<side>.png): its top row and its size
    notes = {
        m = { left = { y = 69, w = 23, h = 180 }, right = { y = 46, w = 24, h = 206 } },
        f = { left = { y = 69, w = 23, h = 183 }, right = { y = 47, w = 24, h = 202 } },
    },
}

-- the chart's pictures' file names, made once (no strings built while drawing)
local LINES_NAME = "fig-chart-lines.png"
local NOTE_NAMES = {
    m = { left = "fig-notes-m-left.png", right = "fig-notes-m-right.png" },
    f = { left = "fig-notes-f-left.png", right = "fig-notes-f-right.png" },
}

-- the chart's pictures, loaded the first time each is drawn, nearest-filtered like the figure (false: missing, asked
-- once)
local _chartTex = {}
local function chartTex(name)
    local t = _chartTex[name]
    if t == nil then
        t = Texture.getSharedTexture(DIR .. name, NEAREST) or false
        _chartTex[name] = t
    end
    return t or nil
end

--- Draw the height chart in the margins of the figure's frame: six draws, and no table made.
-- L is the layout Molecules.figureFrame (or layoutZoneA) gave, and the figure is drawn at its figX, figY, figW, figH
-- (drawAt), as the tabs and the medical card draw it. Call this after Molecules.drawFigureFrame and before the
-- controller's mark and drawAt, so the mark and the figure sit on the chart. Lite draws none.
function ZeD_BodyFigure:drawChart(panel, L)
    -- Lite puts away the extras the game itself does not have (Settings.lua, Lite or Full): the frame stays plain
    if ZeD.Settings and ZeD.Settings.lite and ZeD.Settings.lite() then return end
    local T = ZeD.T
    local C = CHART
    local z = L.zoom                                    -- screen pixels per art pixel: the figure's whole zoom
    local line = T.px(1)                                -- the frame's line, inside its rect (Molecules.drawFigureFrame)
    local figX, figY = L.figX, L.figY
    local figR = figX + L.figW                          -- the canvas's right edge
    -- each margin's width in whole art pixels, from the canvas to the inside of the frame's line
    local sideL = math.floor((figX - (L.frameX + line)) / z)
    local sideR = math.floor((L.frameX + L.frameW - line - figR) / z)
    -- the ruler's own ink (white on the dark bases, near-black on Light, as _background picks its picture), tinted as
    -- drawAt tints the ruler (ZeD.colorBlend(iconWhite, accent, 0.45), worked out here so no table is made)
    local ink = ((T.baseKey or ZeD.currentBase) == "light") and C.inkLight or C.inkDark
    local iw, ac, s = T.iconWhite, T.accent, 0.45
    local inv = 1.0 - s
    local r = ink[1] * (iw.r * inv + ac.r * s)
    local g = ink[2] * (iw.g * inv + ac.g * s)
    local b = ink[3] * (iw.b * inv + ac.b * s)
    -- where the lines run: C.margin art pixels clear of the frame's line and of the canvas (the ruler's numbers)
    local m = C.margin
    local lx0, lx1 = figX - (sideL - m) * z, figX - m * z
    local rx0, rx1 = figR + m * z, figR + (sideR - m) * z
    -- the half-foot lines either side: their picture is a column of the lines' rows, stretched along the side (a
    -- margin too narrow for a line has none)
    local lines = chartTex(LINES_NAME)
    if lines then
        local h = CANVAS_H * z
        if lx1 > lx0 then panel:drawTextureScaled(lines, lx0, figY, lx1 - lx0, h, 1, r, g, b) end
        if rx1 > rx0 then panel:drawTextureScaled(lines, rx0, figY, rx1 - rx0, h, 1, r, g, b) end
    end
    -- the floor, right across under the feet (from lx0 to rx1), leaving the ruler's own floor tick as the ruler
    -- draws it: one piece either side of the tick
    local fy = figY + C.floor * z
    local gx0, gx1 = figX + C.floorGap[1] * z, figX + C.floorGap[2] * z
    local a0, a1 = lx0, math.min(gx0, rx1)
    local b0, b1 = math.max(gx1, lx0), rx1
    if a1 > a0 then panel:drawRect(a0, fy, a1 - a0, z, C.floorA, r, g, b) end
    if b1 > b0 then panel:drawRect(b0, fy, b1 - b0, z, C.floorA, r, g, b) end
    -- the script: each side's words flush with its outer edge, on its lines, where the lines are long enough for its
    -- widest word (a narrow frame keeps the lines alone)
    local sex = self.isFemale and "f" or "m"
    local nl, nr = C.notes[sex].left, C.notes[sex].right
    if lx1 - lx0 >= nl.w * z then
        local t = chartTex(NOTE_NAMES[sex].left)
        if t then panel:drawTextureScaled(t, lx0, figY + nl.y * z, nl.w * z, nl.h * z, C.noteA, r, g, b) end
    end
    if rx1 - rx0 >= nr.w * z then
        local t = chartTex(NOTE_NAMES[sex].right)
        if t then panel:drawTextureScaled(t, rx1 - nr.w * z, figY + nr.y * z, nr.w * z, nr.h * z, C.noteA, r, g, b) end
    end
end

-- the parts over the skeleton: tinted where the tab has something to say, dim otherwise
function ZeD_BodyFigure:_drawParts(panel, xOff, yOff, s)
    for _, entry in ipairs(self.activeLayout) do
        local tex = self.textures[entry.suffix]
        if tex then
            local displayName = SUFFIX_TO_DISPLAY[entry.suffix]
            local color = displayName and self.colorMap[displayName]
            local isHovered = (displayName == self.selectedPart)
            local dx = xOff + math.floor(entry.x * s)
            local dy = yOff + math.floor(entry.y * s)
            if color then
                if isHovered then
                    panel:drawTextureScaledUniform(tex, dx, dy, s, 1.0, 1, 1, 1)
                else
                    panel:drawTextureScaledUniform(tex, dx, dy, s, color.a or 0.9, color.r, color.g, color.b)
                end
            else
                local a = isHovered and 0.20 or 0.10
                panel:drawTextureScaledUniform(tex, dx, dy, s, a, ZeD.T.textDim.r, ZeD.T.textDim.g, ZeD.T.textDim.b)
            end
        end
    end
end

-- ============================================================================
-- COLOR API
