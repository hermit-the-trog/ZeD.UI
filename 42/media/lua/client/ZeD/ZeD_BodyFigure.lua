-- BODY FIGURE — the skeleton the Health, Thermal and Equipment tabs colour.
-- Client-only organism (an ISPanel). Lit pixel art traced over the game's own
-- unclothed male and female bodies (art by ZeDUI/tools/physpx/
-- d_skeleton.py). One 106 x 254 canvas for both sexes, drawn in four layers:
--   1. fig-bg-<s>-<dark|light>.png  the height ruler and the body's outline,
--      tinted by the theme (Graphic cleanup, Nov 22 2026: the room grid is gone)
--   2. <s>-skeleton.png             the lit ivory skeleton on its flesh (muscles,
--      tendons and vessels: Design, Nov 22 2026), untinted
--   3. <s>-<part>.png               each part's bones alone, tinted by the
--      tab (injury, temperature, protection), dim when nothing to say
--   4. wounds/...                   each part's wounds and their care, over the
--      parts (the Health tab and the medical check: setPartWounds, WOUNDS below)
-- Round it, in the margins of the frame the tabs draw it in, drawChart draws
-- the height chart: the ruler's lines out to either side, up to the
-- character's height, and the floor (THE HEIGHT CHART below).
-- s = m / f. The canvas is the figure's own size (ZeD.Spacing.figureW / H),
-- so it is drawn at a whole multiple (1x at 1080p, 2x at 4K) with nearest
-- filtering and the pixels stay square.
-- ============================================================================

